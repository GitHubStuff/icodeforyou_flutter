/// Animation mode presets for [AnimatedPrismBubble].
enum BubbleAnimationEnum {
  /// Rhythmic expansion and contraction of chromatic refraction bands.
  breathing,

  /// Continuous circular swirling of colors around the perimeter.
  liquidRotation,

  /// Simultaneous breathing bloom and liquid rotation.
  combined,
}
